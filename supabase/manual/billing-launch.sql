-- Проверка запуска: SELECT mode,launched_at FROM private.billing_settings WHERE singleton;
-- Существующий кабинет получает 30 дней без лимитов с первого billing_overview()
-- после запуска; дата notice_until хранится на сервере. Действия администратора и
-- команды не запускают и не расходуют персональный срок уведомления собственника.
-- Баннер в приложении показывает её собственнику. До первого взаимодействия старый
-- кабинет не ограничивается. Новый аккаунт получает Portfolio на 30 дней с регистрации,
-- до 20 единиц, без дополнительных мест команды. Trial не получает ещё 7 дней льготы.
-- Оплаченный тариф сохраняется 7 дней после paid_until; затем действует Start (1 единица).
-- На оплату аренды, кабинет арендатора, показания, заявки, историю, чтение и экспорт
-- ограничения подписки не накладываются. Начатые работы/расходы могут завершаться;
-- опубликованное до истечения срока предложение продления может быть принято.
-- Новые договоры/продления и помещения сверх лимита, новые расходы (Owner+),
-- ремонты/новая публикация (Portfolio+), новые приглашения (Team, до 5) защищены БД.
-- Активный объект без помещений = 1 единица; каждое помещение занимает единицу.
-- Архивный объект с незавершённой арендой тоже учитывается. Договор по архивному
-- объекту сначала требует восстановления; занятое помещение удалять нельзя.
-- Чтение финансов и сравнение объектов сохраняется: доступ к существующим данным
-- не отзывается при неоплате. Отдельная тарификация чтения аналитики не реализована.

